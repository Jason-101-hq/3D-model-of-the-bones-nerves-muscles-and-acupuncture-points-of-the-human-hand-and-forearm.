/**
 * 神经真实几何 —— 来自 DiceCT 手部标本（Steer et al. 2026）的中心线重建。
 *
 * 这份数据不是"另一条神经"，而是**换掉**了模型自己那套等直径示意管道的手部段。
 * 每条折线是标本神经表面的中心线（沿弧长 1mm 采样后抽稀），`r` 是同位置的实测半径
 * （表面顶点到截面形心的平均距离）—— 所以粗细是量出来的，不是设的。
 *
 * 采出方式见 _recon/dice2/centerline.py：从腕端切面出发算表面测地距离，
 * 在弧长轴上开重叠窗口取横断面，把跨窗口的同一根管子串成树。分叉点因此是
 * 数据自带的，不是我们定的。后续三步后处理见 gen_nerves.py 抬头：
 * 端点归并（2.5mm 内算同一个分叉点）、链合并（被窗口切碎的管子接回去）、抽稀。
 * 早先试过体素化骨架，会把相距不到 0.7mm 的相邻分支焊成一体、骨架总长虚高
 * 3 倍，已弃用。
 *
 * 坐标系：已是**本项目的模型坐标**（mm、Z 轴向上、+X 桡侧、+Y 背侧），
 * 并与模型共用父级变换。位移由两件事定：X/Y 取标本近端切面处「尺神经→正中神经」
 * 连线与模型腕部走行的对齐；Z 取标本神经指尖落在模型中指远节指骨骨端再外伸 4mm 指腹处。
 * 姿态差（标本手平摊、模型手已前屈约 45°）用一个 (X,Z)→Y 的修正场消掉，
 * 场的锚点全部取自模型自己的神经走行与手骨包围盒 —— 位置来自模型，形态来自标本。
 * 只做平移与这个修正场，没有缩放（两边手尺寸本就近：拇收肌 40.8 vs 39.7mm）。
 *
 * `cap0`/`cap1`：首/尾端是不是**自由端**。自由端要半球收口；接在别的段上的端口
 * 不能收口，否则接缝处被掐细成一个哨。
 *
 * 授权：MorphoSource Media 000868571，开放下载、禁止商业使用。
 */
export interface NervePolyline {
  /** 该段中心线弧长 mm */
  len: number
  /** 采样点（模型坐标 mm） */
  pts: [number, number, number][]
  /** 每个采样点处的实测半径 mm，与 pts 一一对应 */
  r: number[]
  /** 首端是自由端（需要收口） */
  cap0: boolean
  /** 尾端是自由端（需要收口） */
  cap1: boolean
}


